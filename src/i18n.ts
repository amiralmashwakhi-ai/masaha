const dict: Record<Lang, Record<Key, string>> = { en, ar };

export function makeT(lang: Lang) {
  return (key: string) => dict[lang][key as Key] ?? key;
}

// Native RTL flips need an app reload; layout here also mirrors via `isRtl` styles.
export function applyDirection(lang: Lang) {
  const rtl = lang === 'ar';
  if (I18nManager.isRTL !== rtl) {
    I18nManager.allowRTL(rtl);
    I18nManager.forceRTL(rtl);
  }
}
